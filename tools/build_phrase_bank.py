#!/usr/bin/env python3
"""Generate src/Generator/PhraseBankData.h from resources/phrase_bank.json.

  python3 tools/build_phrase_bank.py          # write the header
  python3 tools/build_phrase_bank.py --check  # exit 1 if the header is stale

The JSON holds grammar ingredients only (rhythm cells, degree pools, contours,
variation ops, JACKIN call/answer pairs). PhraseBank.cpp combines them.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "resources" / "phrase_bank.json"
DST = ROOT / "src" / "Generator" / "PhraseBankData.h"

TAGS = {"rest": 0, "sparse": 1, "dense": 2}
OPS = ["same", "retail", "nudge", "last_degree", "drop_one", "pickup_fill", "octave_swap"]
MODES = ["dorian", "aeolian", "phrygian"]


def arr(v):
    return "{ " + ", ".join(str(x) for x in v) + " }" if v else "{}"


def f(x):
    s = repr(float(x))
    return s + "f"


def pad(v, n):
    if len(v) > n:
        raise SystemExit(f"too many entries ({len(v)} > {n}): {v}")
    return list(v) + [0] * (n - len(v))


def emit_style(name, st, out):
    p = f"k{name.capitalize()}"
    out.append(f"inline constexpr PbCell {p}Cells[] = {{")
    for c in st["half_cells"]:
        if len(c["steps"]) != len(c["len"]):
            raise SystemExit(f"{name}/{c['id']}: steps and len differ")
        if any(s < 0 or s > 7 for s in c["steps"]):
            raise SystemExit(f"{name}/{c['id']}: steps must be 0-7")
        out.append(f'    {{ "{c["id"]}", {len(c["steps"])}, {arr(pad(c["steps"], 4))}, {arr(pad(c["len"], 4))}, {f(c["w"])}, {TAGS[c["tag"]]} }},')
    out.append("};")
    out.append(f"inline constexpr PbDeg {p}Degrees[] = {{")
    for d in st["degree_pool"]:
        out.append(f"    {{ {d['deg']}, {f(d['w'])} }},")
    out.append("};")
    out.append(f"inline constexpr PbContour {p}Contours[] = {{")
    for c in st["contours"]:
        out.append(f'    {{ "{c["id"]}", {len(c["deg"])}, {arr(pad(c["deg"], 4))}, {f(c["w"])} }},')
    out.append("};")
    out.append(f"inline constexpr PbVar {p}Vars[] = {{")
    for v in st["variation"]:
        out.append(f"    {{ {OPS.index(v['op'])}, {f(v['w'])} }}, // {v['op']}")
    out.append("};")
    ca = st.get("call_answer")
    if ca:
        out.append(f"inline constexpr PbPair {p}Pairs[] = {{")
        for q in ca["pairs"]:
            out.append(f"    {{ {TAGS[q['call']]}, {TAGS[q['answer']]}, {q['zone'][0]}, {q['zone'][1]}, {q['hits'][0]}, {q['hits'][1]}, {f(q['w'])} }},")
        out.append("};")
        out.append(f"inline constexpr PbVoicing {p}Voicings[] = {{")
        for v in ca["voicings"]:
            out.append(f'    {{ "{v["id"]}", {len(v["stack"])}, {arr(pad(v["stack"], 4))}, {f(v["w"])} }},')
        out.append("};")
        out.append(f"inline constexpr PbDeg {p}AnswerDegrees[] = {{")
        for d in ca["answer_degree"]:
            out.append(f"    {{ {d['deg']}, {f(d['w'])} }},")
        out.append("};")
    o = st["octave"]
    out.append(f"inline constexpr PbStyle {p} {{")
    out.append(f"    {p}Cells, (int) std::size ({p}Cells),")
    out.append(f"    {p}Degrees, (int) std::size ({p}Degrees),")
    out.append(f"    {p}Contours, (int) std::size ({p}Contours),")
    out.append(f"    {p}Vars, (int) std::size ({p}Vars),")
    out.append(f"    {f(o['pop_up'])}, {f(o['drop_down'])}, {f(st['len_scale'][0])}, {f(st['len_scale'][1])},")
    out.append(f"    {f(st['legato'])}, {f(st['ghost'])}, {f(st['glide'])}, {f(st['contour_stray'])}, {f(st['first_root'])}, {f(st['max_len'])},")
    if ca:
        out.append(f"    {p}Pairs, (int) std::size ({p}Pairs),")
        out.append(f"    {p}Voicings, (int) std::size ({p}Voicings),")
        out.append(f"    {p}AnswerDegrees, (int) std::size ({p}AnswerDegrees),")
        out.append(f"    {ca['len'][0]}, {ca['len'][1]}, {f(ca['offbeat_bias'])},")
    else:
        out.append("    nullptr, 0, nullptr, 0, nullptr, 0, 1, 2, 0.5f,")
    out.append("};")
    out.append("")


def build():
    j = json.loads(SRC.read_text(encoding="utf-8"))
    if j.get("schema") != 1:
        raise SystemExit("phrase_bank.json: schema must be 1")
    out = [
        "// Generated by tools/build_phrase_bank.py from resources/phrase_bank.json. Do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "#include <iterator>",
        "",
        "namespace rolla::phrase::data",
        "{",
        "",
        "struct PbCell { const char* id; int n; std::int8_t steps[4]; std::int8_t len[4]; float w; int tag; };",
        "struct PbDeg { int deg; float w; };",
        "struct PbContour { const char* id; int n; std::int8_t deg[4]; float w; };",
        "struct PbVar { int op; float w; };",
        "struct PbPair { int call; int answer; int zoneLo; int zoneHi; int hitsLo; int hitsHi; float w; };",
        "struct PbVoicing { const char* id; int n; std::int8_t stack[4]; float w; };",
        "struct PbStyle",
        "{",
        "    const PbCell* cells; int nCells;",
        "    const PbDeg* degrees; int nDegrees;",
        "    const PbContour* contours; int nContours;",
        "    const PbVar* vars; int nVars;",
        "    float popUp, dropDown, lenLo, lenHi;",
        "    float legato, ghost, glide, stray, firstRoot, maxLen;",
        "    const PbPair* pairs; int nPairs;",
        "    const PbVoicing* voicings; int nVoicings;",
        "    const PbDeg* answerDegrees; int nAnswerDegrees;",
        "    int answerLenLo, answerLenHi; float offbeatBias;",
        "};",
        "",
        "enum Tag : int { TagRest = 0, TagSparse = 1, TagDense = 2 };",
        "enum VarOp : int { " + ", ".join(f"Op{''.join(w.capitalize() for w in o.split('_'))} = {i}" for i, o in enumerate(OPS)) + " };",
        "",
        "inline constexpr int kModes[3][7] = {",
    ]
    for m in MODES:
        out.append(f"    {arr(j['modes'][m])}, // {m}")
    out.append("};")
    out.append(f"inline constexpr int kKickSteps[] = {arr(j['kick_steps'])};")
    out.append(f"inline constexpr float kMaxKickShare = {f(j['max_kick_share'])};")
    out.append("")
    for name in ("deep", "jackin"):
        emit_style(name, j["styles"][name], out)
    out.append("} // namespace rolla::phrase::data")
    return "\n".join(out) + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        if not DST.exists() or DST.read_text(encoding="utf-8") != text:
            print(f"{DST.relative_to(ROOT)} is stale; run tools/build_phrase_bank.py")
            return 1
        print("phrase bank header is current")
        return 0
    DST.write_text(text, encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
