#!/usr/bin/env python3
"""Emit src/Generator/GenreVocab.h from resources/generator/PATTERN_VOCAB.json.

Inference cells keep their style weights in the table. The generator multiplies
those by 0.35 at sample time so a guessed cell is less likely than a sourced one.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "resources" / "generator" / "PATTERN_VOCAB.json"
OUT = ROOT / "src" / "Generator" / "GenreVocab.h"

LANE = {"DRUMS": 0, "BASS": 1, "STAB": 2, "PLUCK": 3, "PAD": 4, "HITS": 5, "VOX": 6}
VOICE = {
    "kick": 0,
    "snare": 1,
    "clap": 2,
    "closed_hat": 6,
    "open_hat": 7,
    "ride": 8,
    "shaker": 9,
    "tamb": 9,
    "perc": 9,
}
STYLES = ("UK_MIN", "LONG", "POP", "GASKIN_90S")


def grid_of(cell):
    g = cell["grid"]
    rows = [g] if isinstance(g, str) else list(g)
    for row in rows:
        if len(row) != 16 or any(ch not in "XxOo-=" for ch in row):
            raise SystemExit(f"bad grid {cell['id']}: {row!r}")
    return "".join(rows), len(rows)


def main():
    data = json.loads(SRC.read_text())
    rows = []
    for lane, cells in data["cells"].items():
        for cell in cells:
            grid, bars = grid_of(cell)
            w = cell.get("style_w") or {}
            weights = ", ".join(f"{float(w.get(s, 0)):.2f}f" for s in STYLES)
            voice = VOICE.get(cell.get("voice"), -1)
            inf = 1 if cell.get("inference") else 0
            ident = cell["id"].replace("\\", "\\\\").replace('"', '\\"')
            rows.append(
                f'    {{ "{ident}", {LANE[lane]}, {voice}, {inf}, {bars}, '
                f"{{ {weights} }}, \"{grid}\" }},"
            )

    text = f"""// Generated by tools/import_genre_vocab.py from resources/generator/PATTERN_VOCAB.json.
// Do not edit by hand. Inference is a flag: sample weight is style_w * 0.35 when it is set.
#pragma once

namespace rolla {{ namespace genre {{

enum Lane : int {{ Drum = 0, Bass = 1, Stab = 2, Pluck = 3, Pad = 4, Hits = 5, Vox = 6 }};

struct Cell {{
    const char* id;
    int lane;
    int voice;
    int inference;
    int bars;
    float w[4];
    const char* grid;
}};

inline constexpr Cell kCells[] = {{
{chr(10).join(rows)}
}};

inline constexpr int kN = {len(rows)};

inline float weight (const Cell& cell, int dialect) noexcept
{{
    const int d = dialect < 0 ? 0 : (dialect > 3 ? 3 : dialect);
    return cell.w[d] * (cell.inference ? 0.35f : 1.f);
}}

}} }}
"""
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(rows)} cells)")


if __name__ == "__main__":
    main()
